def _select_category():
    print("\nFeedback Categories:")
    for index, category in enumerate(FEEDBACK_CATEGORIES, start=1):
        print(f"{index}. {category}")

    choice = validate_menu_choice(
        "Select Category : ",
        [str(index) for index in range(1, len(FEEDBACK_CATEGORIES) + 1)]
    )
    return FEEDBACK_CATEGORIES[int(choice) - 1]


def _select_status(default="Open"):
    print("\nFeedback Status:")
    for index, status in enumerate(FEEDBACK_STATUSES, start=1):
        print(f"{index}. {status}")

    choice = validate_menu_choice(
        f"Select Status ({default}) : ",
        [str(index) for index in range(1, len(FEEDBACK_STATUSES) + 1)]
    )
    return FEEDBACK_STATUSES[int(choice) - 1]


def _feedback_date_optional():
    while True:
        value = input("Follow-up Date (DD-MM-YYYY, optional) : ").strip()
        if not value:
            return None
        from datetime import datetime
        try:
            return datetime.strptime(value, "%d-%m-%Y").strftime("%d-%m-%Y")
        except ValueError:
            print_error("Invalid date. Use DD-MM-YYYY format.")



def _select_follow_up_method():
    print("\nFollow-up Methods:")
    for index, method in enumerate(("Call", "WhatsApp", "Email"), start=1):
        print(f"{index}. {method}")
    choice = validate_menu_choice("Select Follow-up Method : ", ["1", "2", "3"])
